import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const script = join(here, 'srs-coverage.mjs');
const fx = (name, part) => join(here, 'fixtures', name, part);

function run(args, cwd = here) {
  const r = spawnSync(process.execPath, [script, ...args], { encoding: 'utf8', cwd });
  return { code: r.status, out: r.stdout, err: r.stderr };
}

function json(name, extra = []) {
  const r = run([fx(name, 'srs'), '--tests', fx(name, 'tests'), '--json', ...extra]);
  return { code: r.code, ...JSON.parse(r.out) };
}

const rules = (r) => r.findings.map((f) => f.rule).sort();

test('clean fixture: every Accepted Test requirement is cited, exit 0', () => {
  const r = json('clean');
  assert.equal(r.code, 0);
  assert.deepEqual(rules(r), []);
  assert.equal(r.testFilesScanned, 3);
  assert.deepEqual(Object.keys(r.covered).sort(), ['AUTH-SES-01', 'AUTH-USR-01', 'AUTH-USR-03', 'CONN-API-01']);
});

test('underscore IDs in identifiers count only when they match a known requirement', () => {
  const r = json('clean');
  assert.equal(r.covered['CONN-API-01'][0].file.endsWith('test_connector.py'), true);
  assert.equal(r.findings.some((f) => f.id === 'PAGE-SIZE-10'), false, 'test_page_size_10_items is not an ID');
});

test('an ID in a comment is not a citation', () => {
  const r = json('clean');
  assert.equal(r.findings.some((f) => f.id === 'AUTH-USR-77'), false);
});

test('uncovered P1 is reported by priority, exit 1', () => {
  const r = json('uncovered-p1');
  assert.equal(r.code, 1);
  assert.deepEqual(rules(r), ['uncovered']);
  assert.deepEqual(r.uncovered.P1, ['AUTH-USR-03']);
});

test('a test citing a superseded ID is a finding that names the replacement', () => {
  const r = json('superseded-citation');
  assert.equal(r.code, 1);
  assert.deepEqual(rules(r), ['superseded-id']);
  assert.match(r.findings[0].message, /AUTH-USR-02; it was superseded by AUTH-USR-03/);
});

test('a test citing an unknown ID is a finding', () => {
  const r = json('unknown-citation');
  assert.equal(r.code, 1);
  assert.deepEqual(rules(r), ['unknown-id']);
  assert.equal(r.findings[0].id, 'AUTH-USR-99');
});

test('no test files is a finding, never a clean pass', () => {
  const r = json('no-tests');
  assert.equal(r.code, 1);
  assert.ok(rules(r).includes('no-tests'));
});

test('per-area counts combine coverage with trace.md verdicts', () => {
  const r = json('clean');
  const auth = r.areas.find((a) => a.area === 'auth.md');
  assert.deepEqual(
    { accepted: auth.accepted, met: auth.met, partial: auth.partial, cannot: auth.cannot, withTest: auth.withTest, testVerified: auth.testVerified, proposed: auth.proposed },
    { accepted: 3, met: 1, partial: 1, cannot: 1, withTest: 2, testVerified: 2, proposed: 1 },
  );
  assert.equal(r.total.accepted, 4);
  assert.equal(r.total.notMet, 1);
});

function tmpCopy(name) {
  const dir = mkdtempSync(join(tmpdir(), 'srs-coverage-'));
  cpSync(join(here, 'fixtures', name), dir, { recursive: true });
  return dir;
}

test('--write-summary replaces only the block between the markers', () => {
  const dir = tmpCopy('clean');
  try {
    const readme = join(dir, 'srs', 'README.md');
    const before = readFileSync(readme, 'utf8');
    const r = run([join(dir, 'srs'), '--tests', join(dir, 'tests'), '--write-summary', '--date', '2026-11-24']);
    assert.equal(r.code, 0, r.out + r.err);
    const after = readFileSync(readme, 'utf8');
    assert.match(after, /<!-- srs-summary:start -->\nGenerated by srs-coverage on 2026-11-24\./);
    assert.match(after, /\| \*\*Total\*\* \| 4 \| 1 \| 1 \| 1 \| 1 \| 0 \| 3\/3 \| 1 \|\n<!-- srs-summary:end -->/);
    assert.doesNotMatch(after, /Not generated yet/);
    const outside = (s) => s.replace(/<!-- srs-summary:start -->[\s\S]*<!-- srs-summary:end -->/, '');
    assert.equal(outside(after), outside(before));
    const again = run([join(dir, 'srs'), '--tests', join(dir, 'tests'), '--write-summary', '--date', '2026-11-24']);
    assert.equal(again.code, 0);
    assert.equal(readFileSync(readme, 'utf8'), after, 'a second run changes nothing');
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('--write-summary without markers is a finding and leaves the README untouched', () => {
  const dir = tmpCopy('clean');
  try {
    const readme = join(dir, 'srs', 'README.md');
    const stripped = readFileSync(readme, 'utf8').replace('<!-- srs-summary:end -->\n', '');
    writeFileSync(readme, stripped);
    const r = run([join(dir, 'srs'), '--tests', join(dir, 'tests'), '--write-summary', '--json']);
    assert.equal(r.code, 1);
    const out = JSON.parse(r.out);
    assert.equal(out.summaryWritten, false);
    assert.deepEqual(rules(out), ['summary-not-written']);
    assert.equal(readFileSync(readme, 'utf8'), stripped);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('usage errors exit 2', () => {
  assert.equal(run([]).code, 2);
  assert.equal(run([fx('clean', 'srs')]).code, 2, '--tests is required');
  assert.equal(run([fx('clean', 'srs'), '--tests']).code, 2);
  assert.equal(run([fx('clean', 'srs'), '--tests', fx('clean', 'nope')]).code, 2);
  assert.equal(run([fx('clean', 'nope'), '--tests', fx('clean', 'tests')]).code, 2);
  assert.equal(run([fx('clean', 'srs'), '--tests', fx('clean', 'tests'), '--bogus']).code, 2);
  assert.equal(run([fx('clean', 'srs'), '--tests', fx('clean', 'tests'), '--date', 'soon']).code, 2);
});

test('--help exits 0', () => {
  assert.equal(run(['--help']).code, 0);
});
